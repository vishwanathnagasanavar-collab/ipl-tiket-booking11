-- =======================================================
-- IPL MATCH & TICKET BOOKING DATABASE SCHEMA FOR SUPABASE
-- =======================================================
-- Run this script in your Supabase SQL Editor (https://supabase.com/dashboard/project/_/sql)

-- 1. Create MATCHES Table
CREATE TABLE IF NOT EXISTS public.matches (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  team1 TEXT NOT NULL,
  team2 TEXT NOT NULL,
  venue TEXT NOT NULL,
  match_date DATE NOT NULL,
  match_time TIME NOT NULL,
  total_seats INT DEFAULT 50000,
  available_seats INT DEFAULT 50000,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Create BOOKINGS Table
CREATE TABLE IF NOT EXISTS public.bookings (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_name TEXT NOT NULL,
  email TEXT NOT NULL,
  phone TEXT,
  match_id BIGINT REFERENCES public.matches(id) ON DELETE CASCADE,
  seat_type TEXT NOT NULL,
  number_of_tickets INT NOT NULL CHECK (number_of_tickets > 0),
  price_per_ticket NUMERIC NOT NULL,
  total_price NUMERIC NOT NULL,
  booking_status TEXT NOT NULL DEFAULT 'Confirmed',
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. Enable Row Level Security (RLS)
ALTER TABLE public.matches ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.bookings ENABLE ROW LEVEL SECURITY;

-- 4. Create Policies for Anonymous / Public Access
-- Matches policies: anyone can read matches
DROP POLICY IF EXISTS "Public matches read policy" ON public.matches;
CREATE POLICY "Public matches read policy" 
ON public.matches FOR SELECT 
TO anon, authenticated 
USING (true);

-- Allow inserting matches (for seeding or admin)
DROP POLICY IF EXISTS "Public matches insert policy" ON public.matches;
CREATE POLICY "Public matches insert policy" 
ON public.matches FOR INSERT 
TO anon, authenticated 
WITH CHECK (true);

-- Bookings policies: anyone can read, create, and update/cancel bookings
DROP POLICY IF EXISTS "Public bookings read policy" ON public.bookings;
CREATE POLICY "Public bookings read policy" 
ON public.bookings FOR SELECT 
TO anon, authenticated 
USING (true);

DROP POLICY IF EXISTS "Public bookings insert policy" ON public.bookings;
CREATE POLICY "Public bookings insert policy" 
ON public.bookings FOR INSERT 
TO anon, authenticated 
WITH CHECK (true);

DROP POLICY IF EXISTS "Public bookings update policy" ON public.bookings;
CREATE POLICY "Public bookings update policy" 
ON public.bookings FOR UPDATE 
TO anon, authenticated 
USING (true)
WITH CHECK (true);

